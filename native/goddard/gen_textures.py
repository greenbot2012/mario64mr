#!/usr/bin/env python3
"""Goddard's textures (renderer.c's textures/intro_raw/*.inc.c) as blanks of the right size, and a table of them
(gen/gd_texture_table.inc.c, included at the end of the patched renderer.c) that gd_api_set_texture fills at
runtime from the user's data pack: the library itself carries none of the game's data.

Sizes come from the extracted PNGs (width x height x bytes per texel of the N64 format): sm64ex's, made from your ROM.

usage: gen_textures.py <decomp> <extracted textures root (sm64ex)> <out dir>
"""
import re
import struct
import sys
from pathlib import Path

BYTES_PER_TEXEL = {"rgba16": 2, "rgba32": 4, "ia16": 2, "ia8": 1, "i8": 1}

decomp, extracted, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
source = (decomp / "src/goddard/renderer.c").read_text()
found = re.findall(r'static Texture (\w+)\[\] = \{\s*#include "(textures/intro_raw/(\w+)\.(\w+))\.inc\.c"', source)
if not found:
    raise SystemExit("no intro_raw textures in renderer.c")
rows = []
for var, path, name, fmt in found:
    png = (extracted / (path + ".png")).read_bytes()
    if png[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit(f"not a PNG: {path}.png")
    width, height = struct.unpack(">II", png[16:24])
    size = width * height * BYTES_PER_TEXEL[fmt]
    inc = out / (path + ".inc.c")
    inc.parent.mkdir(parents=True, exist_ok=True)
    inc.write_text("/* blank: filled at runtime (gd_api_set_texture) */\n" + "0,\n" * size)
    rows.append(f'    {{ "{name}.{fmt}", {var}, sizeof({var}), {width}, {height} }},')
(out / "gd_texture_table.inc.c").write_text(
    "/* generated by gen_textures.py */\n"
    "struct GdTextureSlot { const char *name; Texture *data; unsigned int size; int width, height; };\n"
    "const struct GdTextureSlot gd_texture_slots[] = {\n" + "\n".join(rows) + "\n};\n"
    "const int gd_texture_slot_count = " + str(len(rows)) + ";\n")
print(f"{len(rows)} blank textures in {out}")
